import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os

# Find the project folder
project_folder = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Create a folder to save charts
charts_folder = os.path.join(project_folder, "charts")
os.makedirs(charts_folder, exist_ok=True)

print("Charts folder created:", charts_folder)

# Locate the CSV file
file_path = os.path.join(
    project_folder,
    "data",
    "sample_sales.csv"
)

# Load the dataset
df = pd.read_csv(file_path)

# Display dataset information
print("Dataset loaded successfully!")

print("\nDataset shape:")
print(df.shape)

print("\nColumn names:")
print(df.columns.tolist())

print("\nFirst 5 rows:")
print(df.head())

# =====================================
# PART 1: SALES KPI ANALYSIS
# =====================================

print("\n========== SALES KPI ANALYSIS ==========")

# Total number of sales records
print("Total Sales Records:", len(df))

# Total units sold
print("Total Units Sold:", df["quantity"].sum())

# Total revenue
print("Total Revenue:", round(df["total"].sum(), 2))

# Average revenue per sale
print("Average Revenue per Sale:", round(df["total"].mean(), 2))

# Highest-value sale
print("Highest Sale Value:", round(df["total"].max(), 2))

# Lowest-value sale
print("Lowest Sale Value:", round(df["total"].min(), 2))

# =====================================
# PART 2: REGIONAL SALES ANALYSIS
# =====================================

print("\n========== REGIONAL SALES ANALYSIS ==========")

# Calculate revenue for each region
regional_sales = df.groupby("region")["total"].sum().sort_values(
    ascending=False
)

print("\nRevenue by Region:")
print(regional_sales)

# Find the best-performing region
best_region = regional_sales.idxmax()

print("\nBest Performing Region:", best_region)
print("Highest Regional Revenue:", round(regional_sales.max(), 2))

# Find the lowest-performing region
lowest_region = regional_sales.idxmin()

print("\nLowest Performing Region:", lowest_region)
print("Lowest Regional Revenue:", round(regional_sales.min(), 2))

# =====================================
# PART 3: PRODUCT PERFORMANCE ANALYSIS
# =====================================

print("\n========== PRODUCT PERFORMANCE ANALYSIS ==========")

# Calculate revenue generated by each product
product_sales = df.groupby("product")["total"].sum().sort_values(
    ascending=False
)

print("\nRevenue by Product:")
print(product_sales)

# Find the best-selling product by revenue
best_product = product_sales.idxmax()

print("\nBest Performing Product:", best_product)
print("Highest Product Revenue:", round(product_sales.max(), 2))

# Find the lowest-performing product by revenue
lowest_product = product_sales.idxmin()

print("\nLowest Performing Product:", lowest_product)
print("Lowest Product Revenue:", round(product_sales.min(), 2))

# Calculate units sold for each product
product_units = df.groupby("product")["quantity"].sum().sort_values(
    ascending=False
)

print("\nUnits Sold by Product:")
print(product_units)

print("\nProduct with Most Units Sold:", product_units.idxmax())
print("Highest Units Sold:", product_units.max())

# =====================================
# PART 4: MONTHLY SALES ANALYSIS
# =====================================

print("\n========== MONTHLY SALES ANALYSIS ==========")

# Convert date column into datetime format
df["date"] = pd.to_datetime(df["date"], format="%d-%m-%Y")

# Extract the month
df["month"] = df["date"].dt.to_period("M")

# Calculate monthly revenue
monthly_sales = df.groupby("month")["total"].sum().sort_index()

print("\nRevenue by Month:")
print(monthly_sales)

# Find the month with the highest revenue
best_month = monthly_sales.idxmax()

print("\nBest Performing Month:", best_month)
print("Highest Monthly Revenue:", round(monthly_sales.max(), 2))

# Find the month with the lowest revenue
lowest_month = monthly_sales.idxmin()

print("\nLowest Performing Month:", lowest_month)
print("Lowest Monthly Revenue:", round(monthly_sales.min(), 2))


# =====================================
# PART 5: DATA VISUALIZATION
# =====================================

# Chart 1: Revenue by Region
plt.figure(figsize=(10, 5))
regional_sales.plot(kind="bar")
plt.title("Regional Sales Analysis")
plt.xlabel("Region")
plt.ylabel("Revenue")

plt.tight_layout()
plt.savefig(os.path.join(charts_folder, "regional_sales.png"), dpi=300)
plt.show()

# Chart 2: Revenue by Product
plt.figure(figsize=(10, 5))
product_sales.plot(kind="barh")
plt.title("Product Revenue Analysis")
plt.xlabel("Revenue")
plt.ylabel("Product")

plt.tight_layout()
plt.savefig(os.path.join(charts_folder, "product_revenue.png"), dpi=300)
plt.show()


# Chart 3: Monthly Sales Trend
plt.figure(figsize=(10, 5))
monthly_sales.plot(kind="line", marker="o")
plt.title("Monthly Sales Trends")
plt.xlabel("Month")
plt.ylabel("Revenue")

plt.tight_layout()
plt.savefig(os.path.join(charts_folder, "monthly_sales.png"), dpi=300)
plt.show()

# =====================================
# PART 6: ADVANCED SALES ANALYSIS
# =====================================

print("\n========== ADVANCED SALES ANALYSIS ==========")

# 1. Descriptive statistics using NumPy
revenue = df["total"].to_numpy()

print("\nRevenue Statistics:")
print("Mean Revenue:", round(np.mean(revenue), 2))
print("Median Revenue:", round(np.median(revenue), 2))
print("Standard Deviation:", round(np.std(revenue), 2))
print("25th Percentile:", round(np.percentile(revenue, 25), 2))
print("75th Percentile:", round(np.percentile(revenue, 75), 2))


# 2. Identify high-value sales
average_revenue = df["total"].mean()

high_value_sales = df[df["total"] > average_revenue]

print("\nNumber of High-Value Sales:")
print(len(high_value_sales))


# 3. Relationship between quantity and revenue
correlation = df["quantity"].corr(df["total"])

print("\nCorrelation Between Quantity and Revenue:")
print(round(correlation, 3))


# 4. Scatter plot using Seaborn
plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=df,
    x="quantity",
    y="total"
)

plt.title("Relationship Between Quantity and Revenue")
plt.xlabel("Quantity Sold")
plt.ylabel("Total Revenue")
plt.tight_layout()
plt.show()


# 5. Revenue distribution using Seaborn
plt.figure(figsize=(10, 6))

sns.histplot(
    data=df,
    x="total",
    bins=20,
    kde=True
)

plt.title("Distribution of Sales Revenue")
plt.xlabel("Revenue per Sale")
plt.ylabel("Number of Sales")
plt.tight_layout()
plt.show()

# =====================================
# PART 7: SALESPERSON PERFORMANCE
# =====================================

print("\n========== SALESPERSON PERFORMANCE ==========")

# 1. Revenue generated by each salesperson
salesperson_revenue = (
    df.groupby("salesperson")["total"]
    .sum()
    .sort_values(ascending=False)
)

print("\nRevenue by Salesperson:")
print(salesperson_revenue.round(2))

# 2. Identify the salesperson with the highest revenue
top_salesperson = salesperson_revenue.idxmax()

print("\nTop Salesperson:", top_salesperson)
print("Highest Revenue:", round(salesperson_revenue.max(), 2))

# 3. Count sales records per salesperson
sales_count = df["salesperson"].value_counts()

print("\nNumber of Sales Records per Salesperson:")
print(sales_count)

# 4. Find the salesperson with the most sales records
most_salesperson = sales_count.idxmax()

print("\nMost Sales Records:", most_salesperson)
print("Number of Records:", sales_count.max())

# 5. Create a bar chart
plt.figure(figsize=(10, 6))

salesperson_revenue.sort_values().plot(kind="barh")

plt.title("Revenue by Salesperson")
plt.xlabel("Total Revenue")
plt.ylabel("Salesperson")
plt.tight_layout()
plt.show()

# =====================================
# PART 8: EXPORT ANALYSIS RESULTS
# =====================================

print("\n========== EXPORTING RESULTS ==========")

# Create a KPI summary
kpi_summary = pd.DataFrame({
    "Metric": [
        "Total Sales Records",
        "Total Units Sold",
        "Total Revenue",
        "Average Revenue per Sale",
        "Highest Sale Value",
        "Lowest Sale Value"
    ],
    "Value": [
        len(df),
        df["quantity"].sum(),
        round(df["total"].sum(), 2),
        round(df["total"].mean(), 2),
        round(df["total"].max(), 2),
        round(df["total"].min(), 2)
    ]
})

# Save results in the project's report folder
report_folder = os.path.join(project_folder, "report")
os.makedirs(report_folder, exist_ok=True)

output_file = os.path.join(
    report_folder,
    "Retail_Sales_Python_Analysis.xlsx"
)

# Export all analyses to separate Excel sheets
with pd.ExcelWriter(output_file) as writer:
    kpi_summary.to_excel(writer, sheet_name="KPI Summary", index=False)
    regional_sales.rename("Revenue").to_frame().to_excel(
        writer, sheet_name="Regional Analysis"
    )
    product_sales.rename("Revenue").to_frame().to_excel(
        writer, sheet_name="Product Analysis"
    )
    monthly_sales.rename("Revenue").to_frame().to_excel(
        writer, sheet_name="Monthly Analysis"
    )
    salesperson_revenue.rename("Revenue").to_frame().to_excel(
        writer, sheet_name="Salesperson Analysis"
    )

print("Excel report exported successfully!")
print("Saved to:", output_file)

# =====================================
# PART 9: FINAL BUSINESS INSIGHTS
# =====================================

print("\n========== FINAL BUSINESS INSIGHTS ==========")

# Overall sales performance
print(f"1. Total revenue generated: {df['total'].sum():,.2f}")

# Best-performing region
print(
    f"2. Best-performing region: {regional_sales.idxmax()} "
    f"with revenue of {regional_sales.max():,.2f}"
)

# Lowest-performing region
print(
    f"3. Lowest-performing region: {regional_sales.idxmin()} "
    f"with revenue of {regional_sales.min():,.2f}"
)

# Best-performing product
print(
    f"4. Best-performing product: {product_sales.idxmax()} "
    f"with revenue of {product_sales.max():,.2f}"
)

# Best-performing month
print(
    f"5. Best-performing month: {monthly_sales.idxmax()} "
    f"with revenue of {monthly_sales.max():,.2f}"
)

# Lowest-performing month
print(
    f"6. Lowest-performing month: {monthly_sales.idxmin()} "
    f"with revenue of {monthly_sales.min():,.2f}"
)

# Top salesperson
print(
    f"7. Top salesperson: {salesperson_revenue.idxmax()} "
    f"with revenue of {salesperson_revenue.max():,.2f}"
)

# Sales volume
print(f"8. Total units sold: {df['quantity'].sum():,}")

print("\nAnalysis completed successfully!")

# =====================================
# PART 10: DATA QUALITY CHECK
# =====================================

print("\n========== DATA QUALITY CHECK ==========")

# 1. Check missing values
print("\nMissing Values by Column:")
print(df.isnull().sum())

# 2. Check duplicate records
duplicate_count = df.duplicated().sum()

print("\nDuplicate Records:", duplicate_count)

# 3. Check data types
print("\nColumn Data Types:")
print(df.dtypes)

# 4. Check for negative quantities
negative_quantity = (df["quantity"] < 0).sum()

print("\nRecords with Negative Quantity:", negative_quantity)

# 5. Check for negative revenue
negative_revenue = (df["total"] < 0).sum()

print("Records with Negative Revenue:", negative_revenue)

# 6. Display dataset dimensions
print("\nTotal Rows:", df.shape[0])
print("Total Columns:", df.shape[1])

print("\nData Quality Check Completed!")


# =====================================
# PART 11: PROFESSIONAL SALES SUMMARY
# =====================================

print("\n========== PROFESSIONAL SALES SUMMARY ==========")

# Create a summary table
sales_summary = pd.DataFrame({
    "Metric": [
        "Total Sales Records",
        "Total Units Sold",
        "Total Revenue",
        "Average Revenue per Sale",
        "Best Performing Region",
        "Lowest Performing Region",
        "Best Performing Product",
        "Best Performing Month",
        "Top Salesperson"
    ],
    "Result": [
        len(df),
        df["quantity"].sum(),
        round(df["total"].sum(), 2),
        round(df["total"].mean(), 2),
        regional_sales.idxmax(),
        regional_sales.idxmin(),
        product_sales.idxmax(),
        str(monthly_sales.idxmax()),
        salesperson_revenue.idxmax()
    ]
})

print(sales_summary.to_string(index=False))

# Export the summary as a CSV file
summary_path = os.path.join(
    report_folder,
    "Retail_Sales_Summary.csv"
)

sales_summary.to_csv(summary_path, index=False)

print("\nSummary saved successfully!")
print("File location:", summary_path)


